// Generates lib/chain/abis.ts from Foundry artifacts. Run after `forge build` (pnpm abi).
// Uses the implementation artifact when it exists (superset: adds AccessControl/Pausable), else the frozen interface.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const pairs = [
  ["RemittanceManager", "IRemittanceManager", "remittanceManagerAbi"],
];
// Canonical signature of an ABI item, e.g. "event Subscribed(uint256,uint256,...)" (tuples expanded).
const typeOf = (i) =>
  i.type.startsWith("tuple") ? `(${i.components.map(typeOf).join(",")})${i.type.slice(5)}` : i.type;
const sigOf = (x) => `${x.type} ${x.name}(${(x.inputs ?? []).map(typeOf).join(",")})`;
const fullSigOf = (x) =>
  `${sigOf(x)}${x.type === "function" ? ` ${x.stateMutability} returns (${(x.outputs ?? []).map(typeOf).join(",")})` : ""}` +
  `${x.type === "event" ? ` indexed[${x.inputs.map((i) => (i.indexed ? 1 : 0)).join("")}]` : ""}`;

let out = "// GENERATED by scripts/export-abi.mjs from contracts/out — do not edit by hand.\n\n";
for (const [impl, iface, id] of pairs) {
  const implPath = `contracts/out/${impl}.sol/${impl}.json`;
  const ifacePath = `contracts/out/${iface}.sol/${iface}.json`;
  const p = existsSync(implPath) ? implPath : ifacePath;
  const abi = JSON.parse(readFileSync(p, "utf8")).abi;
  // Compatibility gate: the implementation must expose every frozen-interface function, event and error with
  // the identical signature, indexing, mutability and return types.
  if (p === implPath && existsSync(ifacePath)) {
    const have = new Set(abi.map(fullSigOf));
    const ifaceAbi = JSON.parse(readFileSync(ifacePath, "utf8")).abi;
    const missing = ifaceAbi.filter((x) => ["function", "event", "error"].includes(x.type) && !have.has(fullSigOf(x)));
    if (missing.length) {
      console.error(`${impl} is missing ${iface} items:\n  ` + missing.map(fullSigOf).join("\n  "));
      process.exit(1);
    }
    console.log(`${impl}: all ${ifaceAbi.length} ${iface} ABI items present`);
  }
  out += `export const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
out += `export const erc20Abi = ${JSON.stringify([
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "owner", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "owner", type: "address" }, { name: "spender", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "spender", type: "address" }, { name: "amount", type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "name", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "nonces", stateMutability: "view", inputs: [{ name: "owner", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "event", name: "Transfer", anonymous: false, inputs: [{ indexed: true, name: "from", type: "address" }, { indexed: true, name: "to", type: "address" }, { indexed: false, name: "value", type: "uint256" }] },
  { type: "event", name: "Approval", anonymous: false, inputs: [{ indexed: true, name: "owner", type: "address" }, { indexed: true, name: "spender", type: "address" }, { indexed: false, name: "value", type: "uint256" }] },
], null, 2)} as const;\n`;
writeFileSync("lib/chain/abis.ts", out);
console.log("wrote lib/chain/abis.ts");
